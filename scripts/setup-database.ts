import {database} from '../server/db';
import {initialTournament} from '../lib/tournament';
const sql=database();
await sql`CREATE TABLE IF NOT EXISTS tournament(id integer PRIMARY KEY CHECK(id=1),data jsonb NOT NULL,revision integer NOT NULL DEFAULT 0,updated_at timestamptz NOT NULL DEFAULT now())`;
await sql`CREATE TABLE IF NOT EXISTS tournament_history(revision integer PRIMARY KEY,action text NOT NULL,previous_data jsonb NOT NULL,created_at timestamptz NOT NULL DEFAULT now())`;
await sql`CREATE TABLE IF NOT EXISTS owner_account(id integer PRIMARY KEY CHECK(id=1),email text NOT NULL,password_hash text NOT NULL)`;
await sql`CREATE TABLE IF NOT EXISTS owner_sessions(token_hash text PRIMARY KEY,expires_at timestamptz NOT NULL)`;
await sql`CREATE TABLE IF NOT EXISTS owner_attempts(ip_hash text PRIMARY KEY,attempts integer NOT NULL,window_start timestamptz NOT NULL)`;
await sql`INSERT INTO tournament(id,data) VALUES(1,${JSON.stringify(initialTournament())}::jsonb) ON CONFLICT(id) DO NOTHING`;
console.log('Tournament tables are ready. Existing data was preserved.');
